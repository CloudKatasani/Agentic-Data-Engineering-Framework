"""Synthetic source databases (the systems of record the first pipeline extracts from).

One deterministic dataset per Domain Pack, rendered three ways:

- SQLite (zero setup): one database file per source schema, attached together, so queries read
  `CRM.SUBSCRIBER` exactly as they would on Oracle or Db2. Built on demand under ADEF_HOME/sources.
- Oracle: schema-only accounts (no passwords) plus tables and data, for Oracle Database Free.
- IBM Db2: schemas, tables and data, for Db2 Community Edition.

Every table also carries LAST_UPDATED_TS, the change watermark an OLTP system typically has,
which the ingestion pipeline uses for incremental extraction.

Connectors read any of them through DB-API and return Arrow tables. Credentials are resolved
from the secret vault by reference and never logged.
"""
from __future__ import annotations

import sqlite3
from datetime import date, datetime, timedelta
from pathlib import Path

from .config import adef_home
from .demo_data import SourceData
from .engine.scenarios import SCENARIOS
from .modeling import physical as ph
from .modeling.logical import parse_type

WATERMARK = "last_updated_ts"
DIALECTS = ("oracle", "db2", "sqlite")


def source_tables(pack: str) -> list[dict]:
    """Source tables for a domain: the scenario's tables, the extra realistic columns from the client
    demo kit when one exists, and the change watermark column."""
    try:
        from .demo_kit import KITS, _sources
        base = _sources(pack) if pack in KITS else [dict(s, columns=list(s["columns"])) for s in SCENARIOS[pack]["sources"]]
    except ImportError:  # pragma: no cover
        base = [dict(s, columns=list(s["columns"])) for s in SCENARIOS[pack]["sources"]]
    out = []
    for s in base:
        cols = list(s["columns"])
        if not any(c["name"] == WATERMARK for c in cols):
            cols.append({"name": WATERMARK, "type": "timestamp", "classification": "internal", "pk": False,
                         "description": "Row last changed (CDC watermark)"})
        out.append({**s, "columns": cols})
    return out


def source_rows(pack: str) -> dict[str, list[dict]]:
    sd = SourceData(pack, sources=source_tables(pack))
    rows = sd.generate()
    base = datetime(2026, 9, 1, 1, 0, 0)
    for t, rs in rows.items():
        for i, r in enumerate(rs):
            r[WATERMARK] = (base + timedelta(minutes=i % 1440)).isoformat(sep=" ")
    return rows


def split(table: str) -> tuple[str, str]:
    schema, name = table.split(".")
    return schema.upper(), name.upper()


# --------------------------------------------------------------------------- SQL rendering
def _literal(v, ltype: str, dialect: str) -> str:
    base, _ = parse_type(ltype)
    if v is None or v == "":
        return "NULL"
    if base == "boolean":
        b = v if isinstance(v, bool) else str(v).lower() in ("1", "true", "t", "y")
        return ("TRUE" if b else "FALSE") if dialect == "db2" else ("1" if b else "0")
    if base in ("integer", "bigint", "decimal"):
        return str(v)
    if base == "date":
        return f"DATE '{str(v)[:10]}'"
    if base == "timestamp":
        return f"TIMESTAMP '{str(v).replace('T', ' ')[:19]}'"
    return "'" + str(v).replace("'", "''") + "'"


def ddl(pack: str, dialect: str) -> str:
    tables = source_tables(pack)
    schemas = sorted({split(s["table"])[0] for s in tables})
    out = [f"-- Synthetic source database for the {pack} demo ({SCENARIOS[pack]['title']})",
           f"-- Dialect: {dialect}. Generated by ADEF; all values are synthetic.", ""]
    if dialect == "oracle":
        out.insert(0, "SET DEFINE OFF")
        out.append("-- Schema-only accounts: they own the tables and cannot log in (no passwords).")
        out += [f"CREATE USER {s} NO AUTHENTICATION QUOTA UNLIMITED ON USERS;" for s in schemas]
    elif dialect == "db2":
        out += [f"CREATE SCHEMA {s};" for s in schemas]
    out.append("")
    for s in tables:
        schema, name = split(s["table"])
        cols = [f"    {c['name'].upper():<26} {ph.phys_type(c['type'], dialect):<18}{' NOT NULL' if c.get('pk') else ''}"
                for c in s["columns"]]
        pks = [c["name"].upper() for c in s["columns"] if c.get("pk")]
        cols.append(f"    CONSTRAINT PK_{name} PRIMARY KEY ({', '.join(pks)})")
        out.append(f"-- {s.get('description', '')}")
        out.append(f"CREATE TABLE {schema}.{name} (\n" + ",\n".join(cols) + "\n);\n")
        if dialect in ("oracle", "db2"):
            out += [f"COMMENT ON COLUMN {schema}.{name}.{c['name'].upper()} IS '{(c.get('description') or '').replace(chr(39), '')}';"
                    for c in s["columns"] if c.get("description")]
            out.append("")
    return "\n".join(out)


def inserts(pack: str, dialect: str, batch: int = 200) -> str:
    tables = {s["table"]: s for s in source_tables(pack)}
    rows = source_rows(pack)
    out = [f"-- Synthetic rows for the {pack} source database ({dialect}). All values are synthetic.", ""]
    if dialect == "oracle":
        out.insert(0, "SET DEFINE OFF")
    for t, rs in rows.items():
        s = tables[t]
        schema, name = split(t)
        cols = [c["name"] for c in s["columns"]]
        types = {c["name"]: c["type"] for c in s["columns"]}
        for i, r in enumerate(rs):
            vals = ", ".join(_literal(r.get(c), types[c], dialect) for c in cols)
            out.append(f"INSERT INTO {schema}.{name} ({', '.join(c.upper() for c in cols)}) VALUES ({vals});")
            if (i + 1) % batch == 0:
                out.append("COMMIT;")
        out.append("COMMIT;")
        out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------- local SQLite source
def sqlite_dir(pack: str, home: Path | None = None) -> Path:
    return (home or adef_home()) / "sources" / pack


def build_sqlite(pack: str, home: Path | None = None, force: bool = False) -> Path:
    """Create one SQLite file per source schema (CRM.sqlite, BSS.sqlite, ...)."""
    import hashlib
    import json as _json
    d = sqlite_dir(pack, home)
    marker = d / ".complete"
    tables = {s["table"]: s for s in source_tables(pack)}
    rows = source_rows(pack)
    digest = hashlib.sha256(_json.dumps([tables, rows], sort_keys=True, default=str).encode()).hexdigest()
    if marker.exists() and marker.read_text().strip() == digest and not force:
        return d  # up to date with the generator
    d.mkdir(parents=True, exist_ok=True)
    for f in d.glob("*.sqlite"):
        f.unlink()
    by_schema: dict[str, list[str]] = {}
    for t in tables:
        by_schema.setdefault(split(t)[0], []).append(t)
    for schema, ts in by_schema.items():
        con = sqlite3.connect(d / f"{schema}.sqlite")
        for t in ts:
            s = tables[t]
            name = split(t)[1]
            cols = s["columns"]
            pks = [c["name"].upper() for c in cols if c.get("pk")]
            con.execute(f"CREATE TABLE {name} (" + ", ".join(
                f"{c['name'].upper()} {ph.phys_type(c['type'], 'sqlite')}" for c in cols) + f", PRIMARY KEY ({', '.join(pks)}))")
            con.executemany(f"INSERT INTO {name} VALUES ({', '.join('?' * len(cols))})",
                            [[_py(r.get(c["name"]), c["type"]) for c in cols] for r in rows[t]])
        con.commit()
        con.close()
    marker.write_text(digest)
    return d


def _py(v, ltype):
    base, _ = parse_type(ltype)
    if v == "" or v is None:
        return None
    if base == "boolean":
        return 1 if (v is True or str(v).lower() in ("1", "true")) else 0
    if base in ("integer", "bigint"):
        return int(v)
    if base == "decimal":
        return float(v)
    if isinstance(v, (date, datetime)):
        return v.isoformat()
    return v


# --------------------------------------------------------------------------- connectors
class SourceConnection:
    """DB-API connection to a source database plus dialect details."""

    def __init__(self, kind: str, con, dialect: str):
        self.kind, self.con, self.dialect = kind, con, dialect

    def tables(self) -> list[str]:
        cur = self.con.cursor()
        if self.kind == "sqlite-local":
            out = []
            for (schema,) in [(r[1],) for r in cur.execute("PRAGMA database_list").fetchall() if r[1] not in ("main", "temp")]:
                out += [f"{schema}.{r[0]}" for r in cur.execute(f"SELECT name FROM {schema}.sqlite_master WHERE type='table'")]
            return sorted(out)
        if self.kind == "oracle":
            cur.execute("SELECT owner || '.' || table_name FROM all_tables WHERE owner IN "
                        "(SELECT username FROM all_users WHERE oracle_maintained = 'N') ORDER BY 1")
        elif self.kind == "db2":
            cur.execute("SELECT TRIM(TABSCHEMA) || '.' || TABNAME FROM SYSCAT.TABLES WHERE TYPE = 'T' AND "
                        "TABSCHEMA NOT LIKE 'SYS%' ORDER BY 1")
        else:
            cur.execute("SELECT table_schema || '.' || table_name FROM information_schema.tables WHERE "
                        "table_schema NOT IN ('pg_catalog','information_schema') ORDER BY 1")
        return [r[0] for r in cur.fetchall()]

    def placeholder(self, n: int = 1) -> str:
        """Positional bind marker for this driver (Oracle :1, PostgreSQL %s, Db2/SQLite ?)."""
        return {"oracle": f":{n}", "postgres": "%s"}.get(self.kind, "?")

    def bind_ts(self, value: str):
        """A watermark value in the form this driver compares correctly against a TIMESTAMP column."""
        if self.kind == "sqlite-local":
            return str(value)
        return datetime.fromisoformat(str(value).replace("T", " ")[:19])

    def query(self, sql: str, params: tuple = ()) -> tuple[list[str], list[tuple]]:
        cur = self.con.cursor()
        cur.execute(sql, params) if params else cur.execute(sql)
        return [d[0].lower() for d in cur.description], cur.fetchall()

    def close(self):
        try:
            self.con.close()
        except Exception:  # noqa: BLE001
            pass


def connect(cfg: dict, secrets=None) -> SourceConnection:
    """cfg: {"type": "sqlite-local", "pack": "telco"} | {"type": "oracle", "dsn": "host:1521/FREEPDB1",
    "user": "system", "password_ref": "secret:oracle-demo"} | {"type": "db2", "host", "port", "database",
    "user", "password_ref"} | {"type": "postgres", "dsn": "...", "password_ref": ...}"""
    kind = cfg.get("type", "sqlite-local")
    if kind == "sqlite-local":
        d = build_sqlite(cfg.get("pack", "utilities"))
        con = sqlite3.connect(":memory:", check_same_thread=False)
        for f in sorted(d.glob("*.sqlite")):
            con.execute(f"ATTACH DATABASE '{f}' AS {f.stem}")
        return SourceConnection(kind, con, "sqlite")
    from .secrets_store import SecretStore
    pw = (secrets or SecretStore()).resolve(cfg.get("password_ref")) if cfg.get("password_ref") else cfg.get("password")
    if kind == "oracle":
        import oracledb  # thin mode: no Oracle client needed
        return SourceConnection(kind, oracledb.connect(user=cfg["user"], password=pw, dsn=cfg["dsn"]), "oracle")
    if kind == "db2":
        try:
            import ibm_db_dbi
        except ImportError as e:
            raise RuntimeError("Db2 sources need the ibm_db driver: pip install ibm_db") from e
        conn_str = (f"DATABASE={cfg['database']};HOSTNAME={cfg['host']};PORT={cfg.get('port', 50000)};"
                    f"PROTOCOL=TCPIP;UID={cfg['user']};PWD={pw};")
        return SourceConnection(kind, ibm_db_dbi.connect(conn_str, "", ""), "db2")
    if kind == "postgres":
        import psycopg
        return SourceConnection(kind, psycopg.connect(cfg["dsn"], password=pw), "postgres")
    raise ValueError(f"unsupported source type {kind}")


def write_seed_scripts(out: Path, packs=None) -> dict[str, int]:
    """Write Oracle and Db2 DDL + data scripts per domain (used by the docker-compose seed containers)."""
    written = {}
    for pack in packs or SCENARIOS:
        for dialect in ("oracle", "db2"):
            d = Path(out) / pack / "source-database" / dialect
            d.mkdir(parents=True, exist_ok=True)
            for name, content in (("01-schema.sql", ddl(pack, dialect)), ("02-data.sql", inserts(pack, dialect))):
                (d / name).write_text(content)
                written[f"{pack}/source-database/{dialect}/{name}"] = len(content.encode())
    return written


def _statements(script: str) -> list[str]:
    """Split a generated seed script into statements (drops SQL*Plus-only lines and comments)."""
    lines = [ln for ln in script.splitlines()
             if ln.strip() and not ln.lstrip().startswith("--") and ln.strip().upper() not in ("SET DEFINE OFF", "EXIT")]
    out, cur = [], []
    for ln in lines:
        cur.append(ln)
        if ln.rstrip().endswith(";"):
            stmt = "\n".join(cur).rstrip().rstrip(";").strip()
            if stmt.upper() != "COMMIT":
                out.append(stmt)
            cur = []
    return out


ALREADY_EXISTS = ("ORA-01920", "ORA-00955", "ORA-01430", "SQL0601N", "SQL0612N", "already exists", "SQLSTATE=42710")


def seed(cfg: dict, pack: str, secrets=None, log=print) -> dict:
    """Create the domain's source schemas, tables and synthetic rows in a real database (Oracle, Db2 or
    PostgreSQL) through its Python driver. Idempotent: existing objects are kept and tables that already
    hold rows are not reloaded."""
    con = connect(cfg, secrets)
    dialect = con.dialect if con.dialect in ("oracle", "db2") else "db2"
    cur = con.con.cursor()
    created = skipped = 0
    for stmt in _statements(ddl(pack, dialect)):
        try:
            cur.execute(stmt)
            created += 1
        except Exception as e:  # noqa: BLE001 - drivers raise different classes
            if any(k in str(e) for k in ALREADY_EXISTS):
                skipped += 1
                continue
            raise
    con.con.commit()
    loaded = {}
    rows = source_rows(pack)
    tables = {s["table"]: s for s in source_tables(pack)}
    for t, rs in rows.items():
        schema, name = split(t)
        cur.execute(f"SELECT COUNT(*) FROM {schema}.{name}")
        if cur.fetchall()[0][0]:
            loaded[t] = "kept (already has rows)"
            continue
        cols = [c["name"] for c in tables[t]["columns"]]
        types = {c["name"]: c["type"] for c in tables[t]["columns"]}
        ph_ = ", ".join(f":{i + 1}" for i in range(len(cols))) if dialect == "oracle" else ", ".join("?" * len(cols))
        sql = f"INSERT INTO {schema}.{name} ({', '.join(c.upper() for c in cols)}) VALUES ({ph_})"
        data = [[_bind(r.get(c), types[c], dialect) for c in cols] for r in rs]
        cur.executemany(sql, data)
        loaded[t] = len(data)
        log(f"seeded {t}: {len(data)} rows")
    con.con.commit()
    con.close()
    return {"objects_created": created, "objects_already_present": skipped, "tables": loaded}


def _bind(v, ltype, dialect):
    base, _ = parse_type(ltype)
    if v is None or v == "":
        return None
    if base == "boolean":
        b = v is True or str(v).lower() in ("1", "true")
        return b if dialect == "db2" else int(b)
    if base in ("integer", "bigint"):
        return int(v)
    if base == "decimal":
        from decimal import Decimal
        return Decimal(str(v))
    if base == "date":
        return date.fromisoformat(str(v)[:10])
    if base == "timestamp":
        return datetime.fromisoformat(str(v).replace("T", " ")[:19])
    return str(v)
